// Writes tests/fixtures/chips.json and tests/android/Expected.kt: expected results from the TypeScript, for the native checks.
import { writeFileSync } from "node:fs";
import { allInScale, breakdown, flightAt, parseChipColours, parseDenominations, pileLayout, shortDenom, sweepToPot } from "../implementation/web/chip-model.ts";

const AMOUNTS = [0, 1, 4, 5, 24, 25, 99, 100, 1337, 5000, 12345, 5000 * 25 + 7];
const SETS = ["casino 5000 1000 500 100 25 5 1", "tokens 100 20 5 1", "units 10 1"];

export function build(): string {
  const breakdowns = SETS.flatMap((set) => AMOUNTS.map((amount) => ({ set, amount, stacks: breakdown(amount, set) })));
  const layouts = [12, 14, 40].flatMap((size) => [1337, 7, 0].map((amount) => ({ size, amount, layout: pileLayout(breakdown(amount), size) })));
  const colours = [["casino", [5000, 1000, 500, 100, 25, 5, 1]], ["mine 25-112233 7-ffffff", [100, 25, 7, 1]], ["casino", [50, 10, 1]]]
    .map(([setting, denoms]) => ({ setting, denoms, colours: parseChipColours(setting as string, denoms as number[]) }));
  const flights = sweepToPot([{ id: "a", amount: 50, from: { x: 0.2, y: 0.4 } }, { id: "c", amount: 25, from: { x: 0.5, y: 0.7 } }], { x: 0.5, y: 0.63 }, { startMs: 100 });
  const along = [0, 0.25, 0.5, 0.75, 1].map((p) => ({ progress: p, point: flightAt(flights[0], p), scale: allInScale(p) }));
  return JSON.stringify({ sets: SETS.map((s) => ({ set: s, denominations: parseDenominations(s) })), breakdowns, layouts, colours, flights, along, short: [1, 25, 999, 1000, 1500, 5000].map((d) => [d, shortDenom(d)]) }, null, 1) + "\n";
}

// Breakdown rows as Kotlin source, so the Android check needs no JSON library: set, amount, then denom:count pairs.
export function buildKotlin(): string {
  const d = JSON.parse(build());
  const rows = d.breakdowns.map((b: any) => `    arrayOf("${b.set}", ${b.amount}, "${b.stacks.map((s: any) => `${s.denom}:${s.count}`).join(" ")}"),`);
  const lay = d.layouts.map((l: any) => `    arrayOf(${l.size}, ${l.amount}, ${l.layout.width}.0, ${l.layout.height}.0, ${l.layout.chips.length}, "${l.layout.chips.map((c: any) => `${c.x}:${c.y}:${Number(c.label)}`).join(" ")}"),`);
  return `// Generated by tests/make-fixtures.ts from the TypeScript chip model.
// set, amount, "denom:count ..." stacks
val EXPECTED_BREAKDOWNS = listOf(
${rows.join("\n")}
)
// size, amount, width, height, chip count, "x:y:label ..."
val EXPECTED_LAYOUTS = listOf(
${lay.join("\n")}
)
`;
}

if (import.meta.main) {
  writeFileSync(new URL("fixtures/chips.json", import.meta.url), build());
  writeFileSync(new URL("android/Expected.kt", import.meta.url), buildKotlin());
}
